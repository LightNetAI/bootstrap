#!/usr/bin/env php
<?php
declare(strict_types=1);

/**
 * Writes config.php, chooses a data directory that respects open_basedir,
 * records the installed file manifest and self-tests the host.
 *
 * Called by install.sh. Safe to re-run with --force.
 */

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}

require dirname(__DIR__) . '/lib/bootstrap.php';

use Bootstrap\BackendClient;
use Bootstrap\Config;
use Bootstrap\Files;
use Bootstrap\GitSsh;
use Bootstrap\Paths;

function out(string $message, bool $json): void
{
    if (!$json) {
        fwrite(STDOUT, $message . PHP_EOL);
    }
}

/** @return array{0: array<string, string>, 1: list<string>} */
function parseArguments(array $argv): array
{
    $options = [];
    $flags = [];
    $count = count($argv);

    for ($i = 1; $i < $count; $i++) {
        $argument = $argv[$i];
        if (!str_starts_with($argument, '--')) {
            continue;
        }
        $body = substr($argument, 2);
        if (str_contains($body, '=')) {
            [$key, $value] = explode('=', $body, 2);
            $options[$key] = $value;
            continue;
        }
        $next = $argv[$i + 1] ?? null;
        if ($next !== null && !str_starts_with($next, '--')) {
            $options[$body] = $next;
            $i++;
            continue;
        }
        $flags[] = $body;
    }

    return [$options, $flags];
}

[$options, $flags] = parseArguments($argv);
$json = in_array('json', $flags, true);
$force = in_array('force', $flags, true);
$skipHealth = in_array('skip-health', $flags, true);
$insecure = in_array('allow-insecure-backend', $flags, true);

$appRoot = dirname(__DIR__);
$webrootOption = $options['webroot'] ?? $appRoot;
$webroot = realpath($webrootOption);
if ($webroot === false || !is_dir($webroot)) {
    fwrite(STDERR, 'Web root does not exist: ' . $webrootOption . PHP_EOL);
    exit(1);
}

$backend = $options['backend'] ?? 'https://bootstrap.dark.net.au';
$backend = rtrim($backend, '/');
$scheme = strtolower((string) parse_url($backend, PHP_URL_SCHEME));
if (!in_array($scheme, ['http', 'https'], true) || parse_url($backend, PHP_URL_HOST) === null) {
    fwrite(STDERR, 'Invalid backend URL: ' . $backend . PHP_EOL);
    exit(1);
}
if ($scheme !== 'https' && !$insecure) {
    fwrite(STDERR, 'The backend URL must use https (add --allow-insecure-backend for local tests).' . PHP_EOL);
    exit(1);
}

$configFile = $webroot . '/config.php';
if (is_file($configFile) && !$force) {
    fwrite(STDERR, 'config.php already exists. Re-run with --force to overwrite it.' . PHP_EOL);
    exit(1);
}

/* ----------------------------------------------------------- data directory */

$dataDir = '';
$candidates = [];
if (isset($options['data-dir']) && $options['data-dir'] !== '') {
    $candidates[] = str_starts_with($options['data-dir'], '/')
        ? rtrim($options['data-dir'], '/')
        : rtrim(getcwd() . '/' . $options['data-dir'], '/');
}
$candidates[] = dirname($webroot) . '/.bootstrap-data-' . substr(sha1($webroot), 0, 10);
$candidates[] = $webroot . '/.bootstrap-data';

foreach ($candidates as $candidate) {
    if (!Paths::allowedByOpenBaseDir($candidate)) {
        continue;
    }
    if (!is_dir($candidate) && !@mkdir($candidate, 0700, true) && !is_dir($candidate)) {
        continue;
    }
    if (is_writable($candidate)) {
        $dataDir = $candidate;
        break;
    }
}

if ($dataDir === '') {
    fwrite(STDERR, 'No writable data directory found inside open_basedir (' . (ini_get('open_basedir') ?: 'not set') . ').' . PHP_EOL);
    exit(1);
}
@chmod($dataDir, 0700);

/* ------------------------------------------------------------------ config */

$values = Config::defaults();
$values['backend_url'] = $backend;
$values['allow_insecure_backend'] = $insecure;
$values['data_dir'] = $dataDir;
$values['install_id'] = bin2hex(random_bytes(8));
$values['installed_at'] = gmdate('c');

if (isset($options['token']) && $options['token'] !== '') {
    $values['github_token'] = $options['token'];
}
if (isset($options['owner']) && $options['owner'] !== '') {
    $values['github_owner'] = $options['owner'];
    if (!isset($options['git-base'])) {
        $values['git_base'] = 'git@github.com:' . $options['owner'];
    }
}
if (isset($options['git-base']) && $options['git-base'] !== '') {
    $values['git_base'] = $options['git-base'];
}

$php = "<?php\ndeclare(strict_types=1);\n\n"
    . "// Generated by bin/configure.php on " . gmdate('c') . ".\n"
    . "// Re-run the installer with --force to regenerate.\n"
    . "return " . var_export($values, true) . ";\n";

if (file_put_contents($configFile, $php, LOCK_EX) === false) {
    fwrite(STDERR, 'Unable to write ' . $configFile . PHP_EOL);
    exit(1);
}
@chmod($configFile, 0600);

/* -------------------------------------------------------------- directories */

Files::ensureDir($dataDir . '/sessions', 0700);
Files::ensureDir($dataDir . '/cache', 0700);
Files::ensureDir($dataDir . '/tmp', 0700);

// If the data directory ended up inside the web root, deny direct access.
if (Paths::isWithin($dataDir, $webroot) && $dataDir !== $webroot) {
    $deny = "<IfModule mod_authz_core.c>\n  Require all denied\n</IfModule>\n"
        . "<IfModule !mod_authz_core.c>\n  Order deny,allow\n  Deny from all\n</IfModule>\n";
    @file_put_contents($dataDir . '/.htaccess', $deny);
    @file_put_contents($dataDir . '/index.html', '');
    @file_put_contents($dataDir . '/sessions/.htaccess', $deny);
    @file_put_contents($dataDir . '/sessions/index.html', '');
}

/* ----------------------------------------------------------------- manifest */

$files = [];
$iterator = new RecursiveIteratorIterator(
    new RecursiveDirectoryIterator($webroot, FilesystemIterator::SKIP_DOTS),
    RecursiveIteratorIterator::LEAVES_ONLY
);
foreach ($iterator as $file) {
    /** @var SplFileInfo $file */
    if (!$file->isFile()) {
        continue;
    }
    $path = $file->getPathname();
    if (str_starts_with($path, $dataDir . '/')) {
        continue;
    }
    if (preg_match('~/\.bs-(stage|old)-~', $path) === 1) {
        continue;
    }
    $relative = ltrim(substr($path, strlen($webroot)), '/');
    $files[] = $relative;
}
sort($files);

$manifest = [
    'generated_at' => gmdate('c'),
    'install_id' => $values['install_id'],
    'version' => BOOTSTRAP_VERSION,
    'files' => $files,
];
@file_put_contents(
    $webroot . '/.bootstrap-manifest.json',
    json_encode($manifest, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . "\n"
);
@chmod($webroot . '/.bootstrap-manifest.json', 0644);

/* ---------------------------------------------------------------- self-test */

$checks = [];
$add = static function (bool $ok, string $label, string $detail, bool $fatal = true) use (&$checks): void {
    $checks[] = ['ok' => $ok, 'label' => $label, 'detail' => $detail, 'fatal' => $fatal];
};

$add(PHP_VERSION_ID >= 80100, 'PHP version', PHP_VERSION . (PHP_VERSION_ID >= 80100 ? '' : ' (8.1+ required)'));
foreach (['curl', 'openssl', 'session', 'json', 'mbstring'] as $extension) {
    $add(extension_loaded($extension), 'Extension: ' . $extension, extension_loaded($extension) ? 'loaded' : 'MISSING');
}
$add(function_exists('proc_open'), 'proc_open()', function_exists('proc_open') ? 'available' : 'DISABLED - git deploys will fail');
$add(is_writable($webroot), 'Web root writable', $webroot);
$add(is_writable($dataDir), 'Data directory writable', $dataDir);
$add(is_writable($dataDir . '/sessions'), 'Session directory writable', $dataDir . '/sessions');

try {
    $config = Config::load($configFile);
    $add(true, 'config.php', 'loads and validates');
} catch (Throwable $exception) {
    $add(false, 'config.php', $exception->getMessage());
    $config = null;
}

try {
    $result = Bootstrap\Process::run(['git', '--version'], [], null, 10);
    $add($result['exit'] === 0, 'git', trim($result['stdout']) ?: 'not found');
} catch (Throwable $exception) {
    $add(false, 'git', $exception->getMessage());
}

$sshOk = function_exists('sodium_crypto_sign_keypair') || function_exists('openssl_pkey_get_private');
$add($sshOk, 'SSH key handling', $sshOk ? 'openssl available' : 'openssl missing');

if ($config !== null && !$skipHealth) {
    try {
        $health = (new BackendClient($config))->health();
        $add($health['ok'], 'BootStrapServer reachable', $health['ok'] ? $backend : $health['error'], false);
    } catch (Throwable $exception) {
        $add(false, 'BootStrapServer reachable', $exception->getMessage(), false);
    }
}

$fatal = 0;
foreach ($checks as $check) {
    if (!$check['ok'] && $check['fatal']) {
        $fatal++;
    }
}

$result = [
    'ok' => $fatal === 0,
    'webroot' => $webroot,
    'data_dir' => $dataDir,
    'backend_url' => $backend,
    'install_id' => $values['install_id'],
    'checks' => $checks,
];

if ($json) {
    fwrite(STDOUT, json_encode($result, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . PHP_EOL);
    exit($fatal === 0 ? 0 : 1);
}

out('', false);
foreach ($checks as $check) {
    $mark = $check['ok'] ? '  ok  ' : ($check['fatal'] ? ' FAIL ' : ' warn ');
    out($mark . ' ' . $check['label'] . ': ' . $check['detail'], false);
}
out('', false);
out('Web root:  ' . $webroot, false);
out('Data dir:  ' . $dataDir, false);
out('Backend:   ' . $backend, false);
out('Installed: ' . count($files) . ' file(s), install id ' . $values['install_id'], false);

exit($fatal === 0 ? 0 : 1);
